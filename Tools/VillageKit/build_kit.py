# Mesh object from an MB

def mb_to_object(mb, name, mats, weighted=True):
    me = bpy.data.meshes.new(name)
    nv = len(mb.V)
    me.vertices.add(nv)
    me.vertices.foreach_set('co', np.asarray(mb.V, np.float32).ravel())
    sizes = np.fromiter((len(f) for f in mb.F), np.int32, len(mb.F))
    starts = np.zeros(len(sizes), np.int32)
    starts[1:] = np.cumsum(sizes)[:-1]
    flat = np.fromiter((i for f in mb.F for i in f), np.int32, int(sizes.sum()))
    me.loops.add(len(flat))
    me.loops.foreach_set('vertex_index', flat)
    me.polygons.add(len(sizes))
    me.polygons.foreach_set('loop_start', starts)
    me.update(calc_edges=True)
    uv = me.uv_layers.new(name='UVMap')
    uv.data.foreach_set('uv', np.fromiter((c for f in mb.UV for p in f for c in p), np.float32, int(sizes.sum()) * 2))
    used = sorted(set(mb.M))
    remap = {m: i for i, m in enumerate(used)}
    for m in used:
        me.materials.append(mats[m])
    me.polygons.foreach_set('material_index', np.fromiter((remap[m] for m in mb.M), np.int32, len(mb.M)))
    me.validate(clean_customdata=False)
    me.polygons.foreach_set('use_smooth', np.ones(len(me.polygons), bool))
    me.set_sharp_from_angle(angle=math.radians(50))
    ob = bpy.data.objects.new(name, me)
    bpy.context.scene.collection.objects.link(ob)
    if weighted:
        wn = ob.modifiers.new('WeightedNormal', 'WEIGHTED_NORMAL')
        wn.mode = 'FACE_AREA'
        wn.weight = 50
        wn.keep_sharp = True
    return ob


def tri_count(ob):
    return sum(len(p.vertices) - 2 for p in ob.data.polygons)


def export_glb(ob, path):
    bpy.ops.object.select_all(action='DESELECT')
    ob.select_set(True)
    bpy.context.view_layer.objects.active = ob
    bpy.ops.export_scene.gltf(filepath=path, export_format='GLB', use_selection=True, export_apply=True,
                              export_yup=True, export_image_format='AUTO', export_materials='EXPORT',
                              export_texcoords=True, export_normals=True, export_extras=False)


