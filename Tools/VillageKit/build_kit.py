# Preview scene

SUN_AZ = 20.0   # world azimuth (deg from +X towards +Y) the HDRI sun is turned to; camera sits at -38


def sky_rotation(img, want_az):
    """Z rotation for the environment mapping that puts the HDRI's sun at azimuth want_az."""
    w, h = img.size
    px = np.empty(w * h * 4, np.float32)
    img.pixels.foreach_get(px)
    px = px.reshape(h, w, 4)
    lum = px[..., 0] * 0.2 + px[..., 1] * 0.7 + px[..., 2] * 0.1
    y, x = np.unravel_index(np.argmax(lum), lum.shape)
    u = (x + 0.5) / w
    phi = (0.5 - u) * 2 * math.pi          # Blender equirect: u = 0.5 - atan2(d.y, d.x) / 2pi
    log('hdri sun at u=%.3f v=%.3f (elev %.1f deg)' % (u, (y + 0.5) / h, ((y + 0.5) / h - 0.5) * 180))
    return phi - math.radians(want_az)


def setup_scene(samples, res):
    sc = bpy.context.scene
    sc.render.engine = 'CYCLES'
    try:
        prefs = bpy.context.preferences.addons['cycles'].preferences
        prefs.compute_device_type = 'METAL'
        prefs.get_devices()
        for d in prefs.devices:
            d.use = True
        sc.cycles.device = 'GPU'
    except Exception as ex:  # noqa: BLE001
        log('GPU unavailable:', ex)
    sc.cycles.samples = samples
    sc.cycles.use_adaptive_sampling = True
    sc.cycles.use_denoising = True
    sc.cycles.max_bounces = 6
    sc.render.resolution_x, sc.render.resolution_y = res
    sc.render.film_transparent = False
    sc.view_settings.view_transform = 'AgX'
    sc.view_settings.look = 'AgX - Medium High Contrast'
    sc.render.image_settings.file_format = 'PNG'
    w = bpy.data.worlds.get('Sky') or bpy.data.worlds.new('Sky')
    sc.world = w
    w.use_nodes = True
    nt = w.node_tree
    nt.nodes.clear()
    o = nt.nodes.new('ShaderNodeOutputWorld')
    bg = nt.nodes.new('ShaderNodeBackground')
    env = nt.nodes.new('ShaderNodeTexEnvironment')
    env.image = bpy.data.images.load(fetch_textures.hdri_path(), check_existing=True)
    mp = nt.nodes.new('ShaderNodeMapping')
    tc = nt.nodes.new('ShaderNodeTexCoord')
    mp.inputs['Rotation'].default_value[2] = sky_rotation(env.image, SUN_AZ)
    nt.links.new(tc.outputs['Generated'], mp.inputs['Vector'])
    nt.links.new(mp.outputs['Vector'], env.inputs['Vector'])
    nt.links.new(env.outputs['Color'], bg.inputs['Color'])
    bg.inputs['Strength'].default_value = 1.0
    nt.links.new(bg.outputs[0], o.inputs[0])
    # ground
    if 'PreviewGround' not in bpy.data.objects:
        bpy.ops.mesh.primitive_plane_add(size=400)
        g = bpy.context.active_object
        g.name = 'PreviewGround'
        gm = make_material('PreviewGround', fetch_textures.tex_path('ground', 'diff'), fetch_textures.tex_path('ground', 'nor_gl'),
                           fetch_textures.tex_path('ground', 'arm'))
        nt = gm.node_tree
        mp = nt.nodes.new('ShaderNodeMapping')
        tc = nt.nodes.new('ShaderNodeTexCoord')
        mp.inputs['Scale'].default_value = (0.5, 0.5, 0.5)
        nt.links.new(tc.outputs['Object'], mp.inputs['Vector'])
        for n in nt.nodes:
            if n.type == 'TEX_IMAGE':
                nt.links.new(mp.outputs['Vector'], n.inputs['Vector'])
        # preview only: darker, patchy northern pasture instead of a uniform tile
        bs = next(n for n in nt.nodes if n.type == 'BSDF_PRINCIPLED')
        td = next(n for n in nt.nodes if n.type == 'TEX_IMAGE' and n.image.colorspace_settings.name != 'Non-Color')
        nz = nt.nodes.new('ShaderNodeTexNoise')
        nz.inputs['Scale'].default_value = 0.08
        nz.inputs['Detail'].default_value = 6
        nt.links.new(tc.outputs['Object'], nz.inputs['Vector'])
        mix = nt.nodes.new('ShaderNodeMix')
        mix.data_type = 'RGBA'
        mix.blend_type = 'MULTIPLY'
        mix.inputs['Factor'].default_value = 1.0
        nt.links.new(td.outputs['Color'], mix.inputs[6])
        ramp = nt.nodes.new('ShaderNodeValToRGB')
        ramp.color_ramp.elements[0].color = (0.16, 0.19, 0.08, 1)
        ramp.color_ramp.elements[1].color = (0.30, 0.32, 0.16, 1)
        nt.links.new(nz.outputs['Fac'], ramp.inputs['Fac'])
        nt.links.new(ramp.outputs['Color'], mix.inputs[7])
        nt.links.new(mix.outputs[2], bs.inputs['Base Color'])
        g.data.materials.append(gm)
        g.location.z = -0.03
    if 'Cam' not in bpy.data.objects:
        cd = bpy.data.cameras.new('Cam')
        cd.lens = 40
        co = bpy.data.objects.new('Cam', cd)
        sc.collection.objects.link(co)
        sc.camera = co


def make_field(model_ob, radius=45.0, count=150000):
    """Preview-only pasture: hair-particle grass on a disc, thinned out where the model
    stands (cells containing wall-height geometry get zero density)."""
    old = bpy.data.objects.get('PreviewField')
    if old:
        bpy.data.objects.remove(old)
    bpy.ops.mesh.primitive_grid_add(x_subdivisions=180, y_subdivisions=180, size=radius * 2)
    f = bpy.context.active_object
    f.name = 'PreviewField'
    f.location.z = -0.02
    co = np.empty(len(model_ob.data.vertices) * 3, np.float32)
    model_ob.data.vertices.foreach_get('co', co)
    co = co.reshape(-1, 3)
    sel = co[(co[:, 2] > 0.25) & (co[:, 2] < 1.6)]
    cell = radius * 2 / 180
    occ = set(map(tuple, np.floor(sel[:, :2] / cell).astype(int)))
    vg = f.vertex_groups.new(name='dens')
    rs = np.random.RandomState(1)
    for v in f.data.vertices:
        x, y = v.co.x, v.co.y
        k = (int(math.floor(x / cell)), int(math.floor(y / cell)))
        blocked = any((k[0] + dx, k[1] + dy) in occ for dx in (-1, 0) for dy in (-1, 0))
        r = math.hypot(x, y)
        wgt = 0.0 if blocked else (1.0 if r < radius * 0.8 else max(0.0, (radius - r) / (radius * 0.2)))
        vg.add([v.index], wgt * (0.6 + 0.4 * rs.rand()), 'REPLACE')
    mod = f.modifiers.new('grass', 'PARTICLE_SYSTEM')
    ps = mod.particle_system
    ps.vertex_group_density = 'dens'
    st = ps.settings
    st.type = 'HAIR'
    st.count = count
    st.hair_length = 0.11
    st.use_advanced_hair = True
    st.normal_factor = 0.11
    st.factor_random = 0.06
    st.child_type = 'INTERPOLATED'
    st.child_percent = 10
    st.rendered_child_count = 12
    st.child_radius = 0.12
    st.child_length = 1.0
    st.child_length_threshold = 0.35
    st.roughness_1 = 0.03
    st.roughness_endpoint = 0.06
    st.roughness_2 = 0.04
    st.clump_factor = 0.25
    st.root_radius = 1.0
    st.tip_radius = 0.0
    st.radius_scale = 0.0045
    st.display_step = 3
    st.render_step = 4
    st.use_hair_bspline = True
    st.length_random = 0.6 if hasattr(st, 'length_random') else 0
    gm = bpy.data.materials.get('PreviewHair')
    if not gm:
        gm = bpy.data.materials.new('PreviewHair')
        gm.use_nodes = True
        nt = gm.node_tree
        bs = nt.nodes['Principled BSDF']
        hi = nt.nodes.new('ShaderNodeHairInfo')
        ramp = nt.nodes.new('ShaderNodeValToRGB')
        ramp.color_ramp.elements[0].color = (0.05, 0.09, 0.02, 1)
        ramp.color_ramp.elements[1].color = (0.24, 0.27, 0.09, 1)
        ramp.color_ramp.elements.new(0.6).color = (0.09, 0.15, 0.035, 1)
        mix = nt.nodes.new('ShaderNodeMix')
        mix.data_type = 'RGBA'
        nt.links.new(hi.outputs['Random'], mix.inputs['Factor'])
        nt.links.new(ramp.outputs['Color'], mix.inputs[6])
        mix.inputs[7].default_value = (0.42, 0.38, 0.2, 1)
        nt.links.new(hi.outputs['Intercept'], ramp.inputs['Fac'])
        mix2 = nt.nodes.new('ShaderNodeMath')
        mix2.operation = 'GREATER_THAN'
        nt.links.new(hi.outputs['Random'], mix2.inputs[0])
        mix2.inputs[1].default_value = 0.8
        nt.links.new(mix2.outputs[0], mix.inputs['Factor'])
        nt.links.new(mix.outputs[2], bs.inputs['Base Color'])
        bs.inputs['Roughness'].default_value = 0.6
    f.data.materials.append(gm)
    return f


def frame_camera(ob, az=-38.0, el=11.0, margin=1.12):
    co = bpy.data.objects['Cam']
    bb = [ob.matrix_world @ Vector(c) for c in ob.bound_box]
    mn = Vector((min(p.x for p in bb), min(p.y for p in bb), max(0.0, min(p.z for p in bb))))
    mx = Vector((max(p.x for p in bb), max(p.y for p in bb), max(p.z for p in bb)))
    c = (mn + mx) / 2
    c.z = (mx.z) * 0.42
    R = (mx - mn).length / 2
    sc = bpy.context.scene
    aspect = sc.render.resolution_x / sc.render.resolution_y
    fov = 2 * math.atan(36 / 2 / co.data.lens)  # horizontal sensor 36mm
    fov_v = 2 * math.atan(math.tan(fov / 2) / aspect)
    dist = R * margin / math.sin(min(fov, fov_v) / 2) * 0.72
    a, e = math.radians(az), math.radians(el)
    d = Vector((math.cos(a) * math.cos(e), math.sin(a) * math.cos(e), math.sin(e)))
    co.location = c + d * dist
    co.rotation_euler = (-d).to_track_quat('-Z', 'Y').to_euler()


def render(path):
    bpy.context.scene.render.filepath = path
    bpy.ops.render.render(write_still=True)


def contact_sheet(names):
    files = [os.path.join(PREV, n + '.png') for n in names if os.path.exists(os.path.join(PREV, n + '.png'))]
    if not files:
        return
    C = 3 if len(files) > 4 else 2
    tw, th = 800, 500
    R = (len(files) + C - 1) // C
    sheet = np.zeros((R * th, C * tw, 4), np.float32)
    sheet[..., 3] = 1
    for i, f in enumerate(files):
        im = bpy.data.images.load(f)
        im.scale(tw, th)
        px = np.empty(tw * th * 4, np.float32)
        im.pixels.foreach_get(px)
        px = px.reshape(th, tw, 4)
        r, c = divmod(i, C)
        y0 = (R - 1 - r) * th
        sheet[y0:y0 + th, c * tw:(c + 1) * tw] = px
        bpy.data.images.remove(im)
    im = bpy.data.images.new('sheet', C * tw, R * th)
    im.pixels.foreach_set(sheet.ravel())
    im.filepath_raw = os.path.join(PREV, 'contact_sheet.png')
    im.file_format = 'PNG'
    im.save()
    log('contact sheet:', [os.path.basename(f) for f in files])


