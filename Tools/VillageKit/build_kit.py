def main():
    import kit_houses
    only = opt('--only', None)
    names = list(kit_houses.RECIPES) if not only else only.split(',')
    samples = opt('--samples', 96, int)
    res = tuple(int(x) for x in opt('--res', '1600x1000').split('x'))
    seed = opt('--seed', 7, int)
    os.makedirs(PREV, exist_ok=True)
    fetch_textures.fetch()
    bpy.ops.wm.read_factory_settings(use_empty=True)
    derive_textures()
    mats = make_materials()
    if not opt('--no-render', False):
        setup_scene(samples, res)
    stats_path = os.path.join(OUT, 'kit_stats.json')
    stats = json.load(open(stats_path)) if os.path.exists(stats_path) else {}
    for name in names:
        rng = random.Random(seed * 1000 + sum(map(ord, name)))
        log('building', name)
        model, dress = kit_houses.RECIPES[name](rng)
        ob = mb_to_object(model, name, mats)
        bb = [Vector(c) for c in ob.bound_box]
        st = {'tris': tri_count(ob), 'verts': len(ob.data.vertices),
              'min': [round(min(p[k] for p in bb), 2) for k in range(3)],
              'max': [round(max(p[k] for p in bb), 2) for k in range(3)],
              'materials': [m.name for m in ob.data.materials]}
        stats[name] = st
        log(name, st)
        if not opt('--no-export', False):
            export_glb(ob, os.path.join(OUT, name + '.glb'))
            log('exported', name + '.glb', '%.1f MB' % (os.path.getsize(os.path.join(OUT, name + '.glb')) / 1e6))
        if not opt('--no-render', False):
            dob = mb_to_object(dress, name + '_dress', mats, weighted=False) if dress.F else None
            make_field(ob)
            frame_camera(ob, az=opt('--az', -38.0, float), el=opt('--el', 8.0, float))
            render(os.path.join(PREV, name + '.png'))
            log('rendered', name)
            if dob:
                bpy.data.objects.remove(dob)
        bpy.data.objects.remove(ob)
    with open(stats_path, 'w') as f:
        json.dump(stats, f, indent=1)
    if opt('--sheet', False) or (not only and not opt('--no-render', False)):
        contact_sheet(list(kit_houses.RECIPES))
    log('done')


