"""
Village building kit for Dragon Flight (UE5): one detailed, photoreal model per
house kind of the North Atlantic fishing village, generated from scratch.

Run headless (Blender 4.5 LTS):
  /Applications/Blender.app/Contents/MacOS/Blender -b -P Tools/VillageKit/build_kit.py -- [options]

Options (after the "--"):
  --only a,b,c       build only these models (e.g. cottage_a,turf_b); default: all
  --no-render        skip preview renders
  --no-export        skip .glb export
  --samples N        Cycles samples for previews (default 96)
  --res WxH          preview resolution (default 1600x1000)
  --sheet            (re)build the contact sheet from the previews on disk
  --seed N           base random seed (default 7); same seed -> identical models

Outputs (Data/ is gitignored for these; everything is regenerated by this script):
  Data/Village/<kind>_<variant>.glb        one mesh object named <kind>_<variant>, textures embedded
  Data/Village/Previews/<name>.png         3/4 daylight Cycles preview
  Data/Village/Previews/contact_sheet.png  all previews tiled
  Data/Village/Textures/                   derived diffuse maps (tar-darkened wood, grass blades)
  Data/Village/kit_stats.json              tri counts and bounds per model

Conventions: metres, Z up, origin at ground centre (stilt houses: bottom of the
posts), main door faces local +X. glTF export uses Blender's standard +Y-up
conversion, so UE Interchange brings it back as X forward, Z up.
"""
