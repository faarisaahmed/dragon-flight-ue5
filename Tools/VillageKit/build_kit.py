def load_px(path):
    im = bpy.data.images.load(path, check_existing=True)
    w, h = im.size
    px = np.empty(w * h * 4, np.float32)
    im.pixels.foreach_get(px)
    return px.reshape(h, w, 4), im


def save_px(px, path, name, quality=92):
    h, w = px.shape[:2]
    if os.path.exists(path):
        os.remove(path)
    im = bpy.data.images.new(name, w, h, alpha=False)
    im.pixels.foreach_set(px.astype(np.float32).ravel())
    im.filepath_raw = path
    im.file_format = 'JPEG'
    bpy.context.scene.render.image_settings.quality = quality
    im.save()
    bpy.data.images.remove(im)


def derive_textures():
    os.makedirs(TEXOUT, exist_ok=True)
    wood, im = load_px(fetch_textures.tex_path('wood', 'diff'))
    rgb = wood[..., :3]
    # Pine tar: much darker, warm brown-black, keeps the grain contrast.
    tar = np.power(rgb, 1.15) * np.array([0.70, 0.60, 0.50]) + 0.01
    out = wood.copy()
    out[..., :3] = np.clip(tar, 0, 1)
    save_px(out, os.path.join(TEXOUT, 'T_Village_WoodTar_D.jpg'), 'wt')
    # Untarred, sun-silvered boards and shingles: slightly lighter and cooler.
    grey = np.clip(np.power(rgb, 1.15) * np.array([0.82, 0.80, 0.76]), 0, 1)
    out[..., :3] = grey
    save_px(out, os.path.join(TEXOUT, 'T_Village_WoodGrey_D.jpg'), 'wg')
    bpy.data.images.remove(im)
    turf, im = load_px(fetch_textures.tex_path('turf', 'diff'))
    turf[..., :3] = np.clip(np.power(turf[..., :3], 1.12) * np.array([0.78, 0.86, 0.6]), 0, 1)
    save_px(turf, os.path.join(TEXOUT, 'T_Village_Turf_D.jpg'), 'tf')
    bpy.data.images.remove(im)
    # Grass blades: columns = blade colour (deep green .. fresh .. olive .. straw), rows = base -> tip.
    W, H = 512, 256
    rs = np.random.RandomState(3)
    u = np.linspace(0, 1, W)
    stops = np.array([0.0, 0.35, 0.68, 0.86, 1.0])
    cols = np.array([[0.15, 0.25, 0.07], [0.26, 0.38, 0.10], [0.36, 0.41, 0.15], [0.48, 0.46, 0.25], [0.6, 0.53, 0.32]])
    base = np.stack([np.interp(u, stops, cols[:, c]) for c in range(3)], -1)
    base *= (0.85 + 0.3 * rs.rand(W, 1))
    v = np.linspace(0, 1, H)[:, None, None]
    shade = 0.45 + 0.6 * np.power(v, 0.6)
    tipdry = np.clip((v - 0.8) / 0.2, 0, 1) * 0.25
    img = base[None] * shade
    img = img * (1 - tipdry) + np.array([0.6, 0.55, 0.38]) * tipdry
    img *= (0.95 + 0.1 * rs.rand(H, W, 1))
    px = np.ones((H, W, 4), np.float32)
    px[..., :3] = np.clip(img, 0, 1)
    save_px(px, os.path.join(TEXOUT, 'T_Village_Grass_D.jpg'), 'gr')


def make_material(name, diff, nor=None, arm=None, rough=0.8, double=False, nor_strength=1.0):
    mat = bpy.data.materials.get(name) or bpy.data.materials.new(name)
    mat.use_nodes = True
    nt = mat.node_tree
    nt.nodes.clear()
    out = nt.nodes.new('ShaderNodeOutputMaterial')
    bsdf = nt.nodes.new('ShaderNodeBsdfPrincipled')
    nt.links.new(bsdf.outputs[0], out.inputs[0])
    td = nt.nodes.new('ShaderNodeTexImage')
    td.image = bpy.data.images.load(diff, check_existing=True)
    nt.links.new(td.outputs['Color'], bsdf.inputs['Base Color'])
    if arm:
        ta = nt.nodes.new('ShaderNodeTexImage')
        ta.image = bpy.data.images.load(arm, check_existing=True)
        ta.image.colorspace_settings.name = 'Non-Color'
        sep = nt.nodes.new('ShaderNodeSeparateColor')
        nt.links.new(ta.outputs['Color'], sep.inputs[0])
        nt.links.new(sep.outputs[1], bsdf.inputs['Roughness'])
        nt.links.new(sep.outputs[2], bsdf.inputs['Metallic'])
    else:
        bsdf.inputs['Roughness'].default_value = rough
    if nor:
        tn = nt.nodes.new('ShaderNodeTexImage')
        tn.image = bpy.data.images.load(nor, check_existing=True)
        tn.image.colorspace_settings.name = 'Non-Color'
        nm = nt.nodes.new('ShaderNodeNormalMap')
        nm.inputs['Strength'].default_value = nor_strength
        nt.links.new(tn.outputs['Color'], nm.inputs['Color'])
        nt.links.new(nm.outputs['Normal'], bsdf.inputs['Normal'])
    mat.use_backface_culling = not double
    return mat


def make_materials():
    ft = fetch_textures
    return [
        make_material(MATS[WOOD], os.path.join(TEXOUT, 'T_Village_WoodTar_D.jpg'), ft.tex_path('wood', 'nor_gl'), ft.tex_path('wood', 'arm')),
        make_material(MATS[GREY], os.path.join(TEXOUT, 'T_Village_WoodGrey_D.jpg'), ft.tex_path('wood', 'nor_gl'), ft.tex_path('wood', 'arm')),
        make_material(MATS[STONE], ft.tex_path('stone', 'diff'), ft.tex_path('stone', 'nor_gl'), ft.tex_path('stone', 'arm')),
        make_material(MATS[TURF], os.path.join(TEXOUT, 'T_Village_Turf_D.jpg'), ft.tex_path('turf', 'nor_gl'), ft.tex_path('turf', 'arm')),
        make_material(MATS[GRASS], os.path.join(TEXOUT, 'T_Village_Grass_D.jpg'), rough=0.75, double=True),
    ]


