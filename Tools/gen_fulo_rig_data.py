#!/usr/bin/env python3
"""Data/Dragon/Fulo/FuloRig.json (Tools/DragonModel/export_fulo.py) -> Source/DragonFlight/Private/DragonFuloRigData.inl

The Night Fury rig by Fulonimation Studios, as tables the game's solver (FDragonFuloRig) reads:
bones in a parents-first order with their Blender rest matrices (armature space, column vectors,
Y along the bone), the file's pose, the constraints the rig uses, and the frames of every
action an ACTION constraint reads.
"""
import json, os, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, 'Data', 'Dragon', 'Fulo', 'FuloRig.json')
OUT = os.path.join(ROOT, 'Source', 'DragonFlight', 'Private', 'DragonFuloRigData.inl')

r = json.load(open(SRC))
bones = r['bones']
names = [b['name'] for b in bones]
# parents first
order, seen = [], set()
byname = {b['name']: b for b in bones}
def visit(n):
    if n in seen: return
    p = byname[n]['parent']
    if p: visit(p)
    seen.add(n); order.append(n)
for n in names: visit(n)
idx = {n: i for i, n in enumerate(order)}

TYPES = {'COPY_ROTATION': 1, 'ACTION': 2, 'STRETCH_TO': 3, 'DAMPED_TRACK': 4, 'COPY_TRANSFORMS': 5, 'IK': 6}
SPACES = {'WORLD': 0, 'POSE': 0, 'LOCAL': 1, 'LOCAL_WITH_PARENT': 2, 'CUSTOM': 3, 'LOCAL_OWNER_ORIENT': 4}
MIX = {'REPLACE': 0, 'ADD': 1, 'BEFORE': 2, 'AFTER': 3, 'OFFSET': 4, 'BEFORE_SPLIT': 5, 'AFTER_SPLIT': 6, 'BEFORE_FULL': 7, 'AFTER_FULL': 8}
CHANNEL = {'LOCATION_X': 0, 'LOCATION_Y': 1, 'LOCATION_Z': 2, 'ROTATION_X': 3, 'ROTATION_Y': 4, 'ROTATION_Z': 5, 'SCALE_X': 6, 'SCALE_Y': 7, 'SCALE_Z': 8}
VOLUME = {'VOLUME_XZX': 0, 'VOLUME_X': 1, 'VOLUME_Z': 2, 'NO_VOLUME': 3}
actions = sorted(r['actions'].keys())
aidx = {a: i for i, a in enumerate(actions)}

def f(v):
    t = ('%.7g' % v).replace('inf', '1e30')
    if '.' not in t and 'e' not in t: t += '.0'
    return t + 'f'

L = []
L.append('// GENERATED by Tools/gen_fulo_rig_data.py from Data/Dragon/Fulo/FuloRig.json')
L.append('// Night Fury model and rig by Fulonimation Studios (https://ko-fi.com/fulonimationstudios).')
L.append('// Blender armature space, column vectors, Y along each bone. Parents precede children.')
L.append('#pragma once')
L.append('static const float GFuloObjectScale = %s;   // the armature object\'s scale: world (constraint) units per armature unit' % f(r.get('object_scale', 0.6894946)))
L.append('struct FFuloBoneDef { const char* Name; int Parent; bool Deform; float Rest[16]; float Length; float Loc[3]; float Rot[4]; float Scale[3]; };')
L.append('struct FFuloConDef { int Owner; int Type; int Target; int OwnerSpace; int TargetSpace; int Mix; float Influence; bool Mute;')
L.append('	bool Use[3]; bool Invert[3]; float HeadTail; int Action; int Channel; float Min; float Max; int FrameStart; int FrameEnd;')
L.append('	float RestLength; float Bulge; int Volume; int ChainCount; int Pole; float PoleAngle; bool UseTail; };')
L.append('struct FFuloActionDef { const char* Name; int FrameStart; int FrameEnd; int FirstTrack; int NumTracks; };')
L.append('struct FFuloTrackDef { int Bone; int FirstKey; };')
L.append('static const FFuloBoneDef GFuloBones[] = {')
for n in order:
    b = byname[n]
    p = idx[b['parent']] if b['parent'] else -1
    rest = b['rest']
    L.append('	{ "%s", %d, %s, { %s }, %s, { %s }, { %s }, { %s } },' % (
        n, p, 'true' if b['deform'] else 'false', ', '.join(f(v) for v in rest), f(b['length']),
        ', '.join(f(v) for v in b['pose_loc']), ', '.join(f(v) for v in b['pose_rot']), ', '.join(f(v) for v in b['pose_scale'])))
L.append('};')
cons = []
for n in order:
    for c in byname[n]['cons']:
        if c['type'] not in TYPES: continue
        tgt = c.get('subtarget') or ''
        t = idx.get(tgt, -1)
        pole = idx.get(c.get('pole_subtarget') or '', -1)
        cons.append('	{ %d, %d, %d, %d, %d, %d, %s, %s, { %s }, { %s }, %s, %d, %d, %s, %s, %d, %d, %s, %s, %d, %d, %d, %s, %s },' % (
            idx[n], TYPES[c['type']], t, SPACES.get(c.get('owner_space') or 'WORLD', 0), SPACES.get(c.get('target_space') or 'WORLD', 0),
            MIX.get(c.get('mix_mode') or 'REPLACE', 0), f(c.get('influence', 1.0)), 'true' if c.get('mute') else 'false',
            ', '.join('true' if c.get('use_' + a, True) else 'false' for a in 'xyz'),
            ', '.join('true' if c.get('invert_' + a, False) else 'false' for a in 'xyz'),
            f(c.get('head_tail') or 0.0), aidx.get(c.get('action'), -1), CHANNEL.get(c.get('transform_channel') or '', -1),
            f(c.get('min') or 0.0), f(c.get('max') or 0.0), int(c.get('frame_start') or 0), int(c.get('frame_end') or 0),
            f(c.get('rest_length') or 0.0), f(c.get('bulge') if c.get('bulge') is not None else 1.0), VOLUME.get(c.get('volume') or 'VOLUME_XZX', 0),
            int(c.get('chain_count') or 0), pole, f(c.get('pole_angle') or 0.0), 'true' if c.get('use_tail', True) else 'false'))
L.append('static const FFuloConDef GFuloCons[] = {')
L += cons
L.append('};')
# actions: tracks (bone, first key) and keys (10 floats per frame: loc xyz, quat wxyz, scale xyz)
tracks, keys = [], []
adefs = []
for a in actions:
    ad = r['actions'][a]
    first = len(tracks)
    # only the bones some ACTION constraint of this action owns
    owners = {n for n in order for c in byname[n]['cons'] if c['type'] == 'ACTION' and c.get('action') == a}
    for bn, frames in ad['bones'].items():
        if bn not in owners or bn not in idx: continue
        tracks.append((idx[bn], len(keys) // 10))
        for fr in frames: keys += fr
    adefs.append((a, ad['frame_start'], ad['frame_end'], first, len(tracks) - first))
L.append('static const FFuloActionDef GFuloActions[] = {')
for a, s, e, ft, nt in adefs: L.append('	{ "%s", %d, %d, %d, %d },' % (a, s, e, ft, nt))
L.append('};')
L.append('static const FFuloTrackDef GFuloTracks[] = {')
for b, k in tracks: L.append('	{ %d, %d },' % (b, k))
L.append('};')
L.append('static const float GFuloKeys[] = {')
for i in range(0, len(keys), 10):
    L.append('	' + ', '.join(f(v) for v in keys[i:i + 10]) + ',')
L.append('};')
open(OUT, 'w').write('\n'.join(L) + '\n')
print('wrote %s: %d bones, %d constraints, %d actions, %d tracks, %d keys' % (OUT, len(order), len(cons), len(adefs), len(tracks), len(keys) // 10))
